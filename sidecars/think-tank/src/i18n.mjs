export function normalizeLang(raw) {
  return String(raw || '').toLowerCase().startsWith('en') ? 'en' : 'fa';
}

export function dirForLang(lang) {
  return normalizeLang(lang) === 'en' ? 'ltr' : 'rtl';
}

export function formatNum(value, lang = 'fa') {
  const str = String(value ?? 0);
  if (normalizeLang(lang) !== 'fa') return str;
  return str.replace(/\d/g, (d) => PERSIAN_DIGITS[Number(d)] || d);
}

export function t(key, params = {}, lang = 'fa') {
  const loc = normalizeLang(lang);
  const dict = TRANSLATIONS[loc] || TRANSLATIONS.fa;
  let out = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  for (const [k, v] of Object.entries(params || {})) {
    const rendered = typeof v === 'number' ? formatNum(v, loc) : String(v ?? '');
    out = out.replaceAll(`{${k}}`, rendered);
  }
  return out;
}

export function actionLabel(raw, lang = 'fa') {
  const loc = normalizeLang(lang);
  const key = String(raw || 'CHAT').trim().toUpperCase();
  return ACTION_LABELS[loc]?.[key] || ACTION_LABELS.en[key] || key;
}

export function stateLabel(raw, lang = 'fa') {
  const loc = normalizeLang(lang);
  const key = String(raw || '').trim();
  return STATE_LABELS[loc]?.[key] || STATE_LABELS[loc]?.[key.toUpperCase()] || key || '-';
}

export function toneForState(raw) {
  const s = String(raw || '').trim().toLowerCase();
  if (['open', 'blocked', 'critical', 'high', 'failed', 'fail', 'error'].includes(s)) return 'open';
  if (['fixing', 'testing', 'in_progress', 'working', 'medium'].includes(s)) return 'working';
  if (['inreview', 'in_review', 'active', 'pending'].includes(s)) return 'review';
  if (['verified', 'closed', 'completed', 'done', 'pass'].includes(s)) return 'verified';
  return 'neutral';
}
